using System.Security.Cryptography;
using System.Text;

namespace GIMI_ModManager.Core.Services.OilGloss;

/// <summary>
/// 油光补丁（KatFXMatcap）的协议常量与命名空间推导。
///
/// 与 <c>InGameMenu</c> 一样，补丁产物全部由 JASM 生成：
/// <list type="bullet">
///   <item><c>JASM_Oil.ini</c>：共享变量（总开关 / 身体 / 衣物）</item>
///   <item><c>JASM_Oil/manifest.json</c>：补丁状态、备份路径与文件哈希</item>
///   <item><c>*.jasm_oil.bak</c>：作者 ini 的原始备份，撤销时还原</item>
/// </list>
///
/// 变量放在独立命名空间，而不是写进每个作者 ini：一个 Mod 可能有
/// <c>norm/mod.ini</c>、<c>ult/mod.ini</c> 等多套文件，写进各自的命名空间后，
/// F7 菜单的一行只能改到其中一套。共享命名空间让所有被补丁的文件引用同一组开关。
/// </summary>
public static class OilGlossProtocol
{
    /// <summary>补丁/清单结构版本；结构变化时递增，旧状态会被视为不兼容。</summary>
    public const int CurrentVersion = 1;

    /// <summary>共享变量所在的 ini 文件名（Mod 根目录）。</summary>
    public const string OilIniFileName = "JASM_Oil.ini";

    /// <summary>补丁状态目录（Mod 根目录）。</summary>
    public const string StateDirectoryName = "JASM_Oil";

    /// <summary>状态清单文件名。</summary>
    public const string ManifestFileName = "manifest.json";

    /// <summary>作者 ini 的备份后缀，如 <c>mod.ini.jasm_oil.bak</c>。</summary>
    public const string BackupSuffix = ".jasm_oil.bak";

    /// <summary>JASM_Oil.ini 的生成标记；没有标记的同名文件绝不覆盖。</summary>
    public const string GeneratedMarker = "; ===== generated by JASM - oil gloss (do not edit) =====";

    /// <summary>KatFXMatcap 本体的命名空间；本体的 <c>[Key*]</c> 行不进菜单。</summary>
    public const string BodyNamespace = "KatFXMatcap";

    /// <summary>本体 ini 的默认文件名（复制到 Mod 根目录时使用）。</summary>
    public const string BodyIniFileName = "Matcap.ini";

    /// <summary>开始给后续 drawcall 上油光的命令。</summary>
    public const string OilSkinCommand = @"run = CommandList\KatFXMatcap\OilSkin";

    /// <summary>结束油光、恢复默认资源的命令。</summary>
    public const string OilClearCommand = @"run = CommandList\KatFXMatcap\Clear";

    /// <summary>总开关变量名（F7 菜单可切换）。</summary>
    public const string MasterVariable = "jasm_oil_on";

    /// <summary>身体组开关变量名。</summary>
    public const string BodyVariable = "oil_body";

    /// <summary>衣物组开关变量名。</summary>
    public const string ClothVariable = "oil_cloth";

    /// <summary>本体里的强度变量名（命名空间 KatFXMatcap，0.0–1.0）。</summary>
    public const string StrengthVariable = "oilstrength";

    /// <summary>
    /// 由 Mod 路径推导稳定的 ASCII 命名空间。
    /// 与 <see cref="GIMI_ModManager.Core.Entities.Mods.InGameMenu.InGameMenuGenerator"/>
    /// 的 <c>Jasm</c> 前缀同思路：路径含中文时，3DMigoto 的表达式解析器会报语法错误。
    /// </summary>
    public static string CreateNamespace(string modFolderPath)
    {
        var seed = (modFolderPath.TrimEnd('\\', '/') + "|" + OilIniFileName).ToLowerInvariant();
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(seed));
        return "JasmOil" + Convert.ToHexString(hash)[..8];
    }

    /// <summary>生成 JASM_Oil.ini 的完整文本（纯 ASCII，避免 3DMigoto 编码问题）。</summary>
    public static string BuildOilIniText(string ns)
    {
        var newLine = "\r\n";
        var lines = new[]
        {
            GeneratedMarker,
            "namespace = " + ns,
            "",
            "[Constants]",
            "global persist $" + MasterVariable + " = 1",
            "global persist $" + BodyVariable + " = 1",
            // 衣物默认关闭：多数 Mod 的「衣物」分组会带上裙摆/配饰，默认全开会把整身都打亮；
            // 想要衣物油光时在 F7 菜单里点一下「衣物油光」即可。
            "global persist $" + ClothVariable + " = 0",
            "",
            "[End of file.]",
            "",
        };

        return string.Join(newLine, lines);
    }
}

/// <summary>drawcall 属于哪一组油光开关。</summary>
public enum OilGlossGroup
{
    Body,
    Cloth,
}

/// <summary>补丁状态。</summary>
public enum OilGlossState
{
    NotApplied,
    Applied,
    /// <summary>补丁在，但备份/产物缺失（例如 Mod 被更新覆盖），需要重新开启。</summary>
    Broken,
    /// <summary>撤销时发现作者 ini 被外部修改过，拒绝覆盖。</summary>
    Conflict,
}

/// <summary>扫描到的一个 drawindexed。</summary>
public sealed record OilGlossDrawcall
{
    /// <summary>相对 Mod 根目录的 ini 路径。</summary>
    public required string IniRelativePath { get; init; }

    /// <summary>所属段落名（不含方括号），如 <c>TextureOverrideComponent4</c>。</summary>
    public required string SectionName { get; init; }

    /// <summary>drawindexed 在文件中的行号（0 基）。补丁前会重新扫描，不直接信任它。</summary>
    public required int LineIndex { get; init; }

    /// <summary>索引数量（第一个参数），用于按大小自动分组。</summary>
    public required int IndexCount { get; init; }

    /// <summary>起始索引（第二个参数）。</summary>
    public required int StartIndex { get; init; }

    /// <summary>同一段落里最近的 <c>if $变量</c>，用于判断头部/部位。</summary>
    public string Condition { get; init; } = string.Empty;

    /// <summary>最近的 <c>ResourceTexture*</c> 贴图槽。</summary>
    public string TextureSlot { get; init; } = string.Empty;

    /// <summary>drawcall 上方紧邻的 <c>; Draw ...</c> 注释。</summary>
    public string Comment { get; init; } = string.Empty;

    /// <summary>是否被判定为头部/头发/脸（默认不包油光）。</summary>
    public bool IsHeadLike { get; init; }

    /// <summary>
    /// 条件变量在默认形态下是否为真；<c>null</c> 表示无法求值（按可见处理）。
    /// 自动分组优先选可见的 drawcall，避免把补丁打到默认不绘制的网格上。
    /// </summary>
    public bool? VisibleByDefault { get; init; }

    /// <summary>自动分组结果；<c>null</c> 表示未被选中。</summary>
    public OilGlossGroup? Group { get; init; }
}

/// <summary>扫描结果与自动分组。</summary>
public sealed record OilGlossScanResult
{
    public IReadOnlyList<OilGlossDrawcall> Drawcalls { get; init; } = [];

    /// <summary>身体组（索引数最大的一块）。</summary>
    public OilGlossDrawcall? Body { get; init; }

    /// <summary>衣物组（排除头部后、除身体外最大的一块）。</summary>
    public OilGlossDrawcall? Cloth { get; init; }

    /// <summary>没有可包 drawcall 时的原因。</summary>
    public string Reason { get; init; } = string.Empty;

    public bool HasSelection => Body is not null || Cloth is not null;
}

/// <summary>一个被补丁的作者 ini。</summary>
public sealed class OilGlossPatchedFile
{
    public string RelativePath { get; set; } = string.Empty;
    public string BackupRelativePath { get; set; } = string.Empty;
    public string PatchedSha256 { get; set; } = string.Empty;
}

/// <summary>JASM 复制进 Mod 的本体资源。</summary>
public sealed class OilGlossAssetRecord
{
    public string RelativePath { get; set; } = string.Empty;
    public string Sha256 { get; set; } = string.Empty;
}

/// <summary>补丁状态清单（<c>JASM_Oil/manifest.json</c>）。</summary>
public sealed class OilGlossManifest
{
    public int ManifestVersion { get; set; } = OilGlossProtocol.CurrentVersion;
    public int GeneratorVersion { get; set; } = OilGlossProtocol.CurrentVersion;
    public string Namespace { get; set; } = string.Empty;
    public bool BodyProvidedByJasm { get; set; }
    public List<OilGlossAssetRecord> BodyFiles { get; set; } = [];
    public List<OilGlossPatchedFile> PatchedFiles { get; set; } = [];
    public bool HasBodyGroup { get; set; }
    public bool HasClothGroup { get; set; }
    public DateTime AppliedAtUtc { get; set; }
}

/// <summary>读盘得到的状态。</summary>
public sealed record OilGlossStatus
{
    public required OilGlossState State { get; init; }
    public OilGlossManifest? Manifest { get; init; }
    public string Reason { get; init; } = string.Empty;
}

/// <summary>Apply 的结果。</summary>
public sealed record OilGlossApplyResult
{
    public required OilGlossApplyStatus Status { get; init; }
    public string Reason { get; init; } = string.Empty;
    public OilGlossManifest? Manifest { get; init; }
    public int BodyCount { get; init; }
    public int ClothCount { get; init; }
}

public enum OilGlossApplyStatus
{
    Applied,
    AlreadyApplied,
    NoDrawcalls,
    Failed,
}

/// <summary>撤销的结果。</summary>
public sealed record OilGlossUndoResult
{
    public required bool Success { get; init; }
    public IReadOnlyList<string> RestoredFiles { get; init; } = [];
    public IReadOnlyList<string> Conflicts { get; init; } = [];
    public string Reason { get; init; } = string.Empty;
}

/// <summary>本体资源来源（生产环境读内嵌资源，测试用内存字典）。</summary>
public interface IOilGlossAssetSource
{
    /// <summary>相对路径，如 <c>Matcap.ini</c> / <c>Oil/MC1.dds</c>（正斜杠）。</summary>
    IReadOnlyList<string> AssetPaths { get; }

    Stream? OpenRead(string relativePath);
}

/// <summary>本体复制结果。</summary>
public sealed record OilGlossBodyProvisionResult
{
    /// <summary>Mod 里原本就有 KatFXMatcap 本体（不覆盖）。</summary>
    public bool AlreadyPresent { get; init; }

    /// <summary>这次由 JASM 写入的文件。</summary>
    public IReadOnlyList<OilGlossAssetRecord> WrittenFiles { get; init; } = [];

    public string Reason { get; init; } = string.Empty;

    public bool Success { get; init; }
}